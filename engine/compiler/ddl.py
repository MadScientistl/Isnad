from __future__ import annotations

from pathlib import Path

from .exprs import current_pred, eff_pred, filter_to_sql, subtype_names
from .model import GEO_TYPES, Ontology, snake_case

PG_TYPES = {"string": "text", "int": "bigint", "float": "double precision",
            "bool": "boolean", "timestamp": "timestamptz",
            "point": "geometry(Point,4326)", "linestring": "geometry(LineString,4326)"}

COMMON = """    valid_during tstzrange NOT NULL,
    recorded_during tstzrange NOT NULL,
    changed_by text NOT NULL,
    action_id uuid NULL,
    scenario_id int NOT NULL DEFAULT 0"""

CURRENT = ("(upper_inf(recorded_during) OR upper(recorded_during) = 'infinity') AND valid_during @> now() AND scenario_id = 0")


_GOVERNANCE_SQL = Path(__file__).resolve().parents[1] / "db" / "governance.sql"


def scenario_core_sql() -> str:
    """The `-- BEGIN scenario_core` .. `-- END scenario_core` section of engine/db/governance.sql (roles,
    scenario tables, GUC readers, access functions). Spliced into the generated DDL so that a schema built from
    the compiler output alone has everything the eff_* views and scenario policies reference."""
    text = _GOVERNANCE_SQL.read_text()
    a = text.index("-- BEGIN scenario_core")
    b = text.index("-- END scenario_core")
    return text[a:b] + "-- END scenario_core\n"


def q(s: str) -> str:
    return '"' + s.replace('"', '""') + '"'


def lit(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


APP_ROLE = "amarh_app"
ROLE_SQL = "current_setting('amarh.role', true)"


def generate_ddl(o: Ontology) -> str:
    """Everything: tables, indexes, cur_* views and the whole policy layer (schema.sql)."""
    return generate_base_ddl(o) + "\n" + generate_policy_ddl(o)


def generate_base_ddl(o: Ontology) -> str:
    out = ["-- Generated by engine.compiler. Do not edit.",
           "CREATE EXTENSION IF NOT EXISTS btree_gist;", "CREATE EXTENSION IF NOT EXISTS postgis;", "",
           scenario_core_sql(),
           "CREATE TABLE IF NOT EXISTS graph_outbox (",
           "    seq bigserial PRIMARY KEY,", "    kind text,", "    type text,", "    id uuid,",
           "    src uuid,", "    dst uuid,", "    op text,", "    at timestamptz DEFAULT now()", ");", "",
           "DROP TRIGGER IF EXISTS amarh_no_scn ON graph_outbox;",
           "CREATE TRIGGER amarh_no_scn BEFORE INSERT ON graph_outbox FOR EACH ROW "
           "EXECUTE FUNCTION amarh_no_scenario_write();", "",
           "CREATE TABLE IF NOT EXISTS ontology_registry (",
           "    hash text PRIMARY KEY,", "    yaml text,", "    applied_at timestamptz", ");", ""]
    for name in sorted(o.object_types):
        t = o.object_types[name]
        tbl = f"obj_{t.snake}"
        cols = ["    id uuid NOT NULL"]
        checks = []
        geo_idx = []
        for p in t.properties:
            nn = " NOT NULL" if p.required else ""
            if p.type == "enum":
                cols.append(f"    {q(p.name)} text{nn}")
                vals = ", ".join(lit(v) for v in p.enum)
                checks.append(f"    CONSTRAINT {q(f'{tbl}_{p.name}_check')} CHECK ({q(p.name)} IS NULL OR {q(p.name)} IN ({vals}))")
            else:
                cols.append(f"    {q(p.name)} {PG_TYPES[p.type]}{nn}")
                if p.type in GEO_TYPES:
                    geo_idx.append(f"CREATE INDEX IF NOT EXISTS {q(f'{tbl}_{p.name}_gist')} ON {tbl} USING gist ({q(p.name)});")
        body = ",\n".join(cols + [COMMON] + checks + [
            f"    CONSTRAINT {q(f'{tbl}_no_overlap')} EXCLUDE USING gist (scenario_id WITH =, id WITH =, valid_during WITH &&, recorded_during WITH &&)"])
        out += [f"CREATE TABLE IF NOT EXISTS {tbl} (", body, ");",
                f"CREATE INDEX IF NOT EXISTS {q(f'{tbl}_id_idx')} ON {tbl} (id);",
                f"CREATE INDEX IF NOT EXISTS {q(f'{tbl}_scn_id_idx')} ON {tbl} (scenario_id, id);", *geo_idx,
                f"CREATE OR REPLACE VIEW cur_{tbl} WITH (security_invoker = true) AS SELECT * FROM {tbl} WHERE {CURRENT};",
                f"CREATE OR REPLACE VIEW eff_{tbl} WITH (security_invoker = true) AS SELECT * FROM {tbl} a "
                f"WHERE {eff_pred('a', 'obj', name)};", ""]
    for name in sorted(o.link_types):
        tbl = f"link_{name}"
        body = ",\n".join(["    src uuid NOT NULL", "    dst uuid NOT NULL", COMMON,
            f"    CONSTRAINT {q(f'{tbl}_no_overlap')} EXCLUDE USING gist (scenario_id WITH =, src WITH =, dst WITH =, valid_during WITH &&, recorded_during WITH &&)"])
        out += [f"CREATE TABLE IF NOT EXISTS {tbl} (", body, ");",
                f"CREATE INDEX IF NOT EXISTS {q(f'{tbl}_src_idx')} ON {tbl} (src);",
                f"CREATE INDEX IF NOT EXISTS {q(f'{tbl}_dst_idx')} ON {tbl} (dst);",
                f"CREATE INDEX IF NOT EXISTS {q(f'{tbl}_scn_src_idx')} ON {tbl} (scenario_id, src);",
                f"CREATE INDEX IF NOT EXISTS {q(f'{tbl}_scn_dst_idx')} ON {tbl} (scenario_id, dst);",
                f"CREATE OR REPLACE VIEW cur_{tbl} WITH (security_invoker = true) AS SELECT * FROM {tbl} WHERE {CURRENT};",
                f"CREATE OR REPLACE VIEW eff_{tbl} WITH (security_invoker = true) AS SELECT * FROM {tbl} a "
                f"WHERE {eff_pred('a', 'link', name)};", ""]
    return "\n".join(out)


# ------------------------------------------------------------------ policy layer
def _role_case(arms: list[tuple[str, str]], default: str = "false") -> str:
    """CASE over amarh.role; unset/unknown role falls to `default` (fail closed)."""
    if not arms:
        return default
    body = " ".join(f"WHEN {lit(r)} THEN {e}" for r, e in arms)
    return f"CASE {ROLE_SQL} {body} ELSE {default} END"


def _endpoint_vis(o: Ontology, target: str, col: str) -> str:
    names = subtype_names(o, target)
    if not names:
        return "false"
    return "(" + " OR ".join(f"amarh_visible_{snake_case(n)}({col})" for n in names) + ")"


def generate_policy_ddl(o: Ontology) -> str:
    """Roles, SECURITY DEFINER visibility helpers, FORCE RLS + policies, masking views, grants.

    Notes:
    * Policies are `TO amarh_app` only. The owner (the connection user: loader, migrations, sync,
      reasoner) is exempted from FORCE by an `amarh_owner` policy (and a superuser bypasses RLS
      entirely, which is the dev setup). Only `SET LOCAL ROLE amarh_app` requests are filtered.
    * Unset/unknown amarh.role matches no CASE arm: zero rows, writes denied.
    """
    out = ["-- ---- policy layer (roles, row-level security, masking views, grants) ----",
           "DO $$ BEGIN",
           f"  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '{APP_ROLE}') THEN",
           f"    BEGIN CREATE ROLE {APP_ROLE} NOLOGIN;",
           "    EXCEPTION WHEN duplicate_object OR unique_violation THEN NULL;",
           "    END;", "  END IF;", "END $$;", "",
           f"DO $$ BEGIN IF NOT has_schema_privilege('{APP_ROLE}', current_schema(), 'USAGE') THEN",
           f"  EXECUTE format('GRANT USAGE ON SCHEMA %I TO {APP_ROLE}', current_schema()); END IF; END $$;", ""]
    roles = sorted(o.roles)
    types = sorted(o.object_types)

    # 1. visibility helpers (current version of the object id decides, D4)
    for t in types:
        snake = snake_case(t)
        arms = []
        for rn in roles:
            acc = o.roles[rn].types.get(t)
            if not acc or not acc.read:
                continue
            if acc.where_ast is None:
                arms.append((rn, "p_id IS NOT NULL"))
            else:
                flt = filter_to_sql(acc.where_ast, o, t, "t")
                arms.append((rn, f"EXISTS (SELECT 1 FROM obj_{snake} t WHERE t.id = p_id AND {current_pred('t', 'obj', t)} AND {flt})"))
        out += [f"CREATE OR REPLACE FUNCTION amarh_visible_{snake}(p_id uuid) RETURNS boolean",
                "LANGUAGE sql STABLE SECURITY DEFINER AS $fn$",
                f"SELECT {_role_case(arms)}", "$fn$;",
                # pg_temp LAST (and pg_catalog first): temp objects can never shadow the real tables
                f"DO $do$ BEGIN EXECUTE format('ALTER FUNCTION amarh_visible_{snake}(uuid) SET search_path = "
                f"pg_catalog, %I, public, pg_temp', current_schema()); END $do$;",
                f"REVOKE ALL ON FUNCTION amarh_visible_{snake}(uuid) FROM PUBLIC;",
                f"GRANT EXECUTE ON FUNCTION amarh_visible_{snake}(uuid) TO {APP_ROLE};", ""]

    def owner_policy(tbl):
        return [f"DROP POLICY IF EXISTS amarh_owner ON {tbl};",
                f"CREATE POLICY amarh_owner ON {tbl} FOR ALL TO CURRENT_USER USING (true) WITH CHECK (true);"]

    def enable(tbl):
        return [f"ALTER TABLE {tbl} ENABLE ROW LEVEL SECURITY;", f"ALTER TABLE {tbl} FORCE ROW LEVEL SECURITY;"]

    # a row of scenario N is reachable only inside scenario N (GUC set server-side) and only while the caller may
    # see (read) / own (write) it; main rows (scenario_id = 0) are unaffected (the OR short-circuits; plain
    # function calls, no sub-selects, so the main-path plan keeps no InitPlans).
    scn_r = "(scenario_id = 0 OR (scenario_id = amarh_scn() AND amarh_scenario_visible(scenario_id)))"
    # writes: main rows only while NO scenario is active; scenario rows only into the active scenario
    scn_w = ("((scenario_id = 0 AND amarh_scn() = 0) OR "
             "(scenario_id = amarh_scn() AND amarh_scenario_writable(scenario_id)))")

    def policies(tbl, sel, ins, upd_using, upd_check):
        out2 = []
        for nm in ("amarh_select", "amarh_insert", "amarh_update"):
            out2.append(f"DROP POLICY IF EXISTS {nm} ON {tbl};")
        out2 += [f"CREATE POLICY amarh_select ON {tbl} FOR SELECT TO {APP_ROLE} USING ({scn_r} AND {sel});",
                 f"CREATE POLICY amarh_insert ON {tbl} FOR INSERT TO {APP_ROLE} WITH CHECK ({scn_w} AND {ins});",
                 f"CREATE POLICY amarh_update ON {tbl} FOR UPDATE TO {APP_ROLE} USING ({scn_w} AND {upd_using}) "
                 f"WITH CHECK ({scn_w} AND {upd_check});"]
        return out2

    # 2. object tables
    for t in types:
        snake = snake_case(t)
        tbl = f"obj_{snake}"
        w_arms, i_arms, r_arms = [], [], []
        for rn in roles:
            racc = o.roles[rn].types.get(t)
            if racc and racc.read:  # D4: the filter must also hold on the version row itself
                r_arms.append((rn, "true" if racc.where_ast is None else filter_to_sql(racc.where_ast, o, t, tbl)))
            acc = o.roles[rn].types.get(t)
            if not acc or not acc.write:
                continue
            w_arms.append((rn, "true"))
            i_arms.append((rn, "true" if acc.where_ast is None else filter_to_sql(acc.where_ast, o, t, tbl)))
        out += enable(tbl) + owner_policy(tbl)
        out += policies(tbl, f"amarh_visible_{snake}(id) AND {_role_case(r_arms)}", _role_case(i_arms),
                        f"{_role_case(w_arms)} AND amarh_visible_{snake}(id)", _role_case(i_arms))
        out.append("")

    # 3. link tables
    for ln in sorted(o.link_types):
        l = o.link_types[ln]
        tbl = f"link_{ln}"
        vis = f"{_endpoint_vis(o, l.src, 'src')} AND {_endpoint_vis(o, l.dst, 'dst')}"
        r_arms, w_arms = [], []
        src_types = subtype_names(o, l.src)
        for rn in roles:
            r = o.roles[rn]
            if ln not in r.links:
                continue
            r_arms.append((rn, "true"))
            if any(r.can_write(st) for st in src_types):
                w_arms.append((rn, "true"))
        out += enable(tbl) + owner_policy(tbl)
        out += policies(tbl, f"{_role_case(r_arms)} AND {vis}", f"{_role_case(w_arms)} AND {vis}",
                        f"{_role_case(w_arms)} AND {vis}", _role_case(w_arms))
        out.append("")

    # 4. masking views (security_invoker: RLS of the caller applies)
    for t in types:
        snake = snake_case(t)
        tbl = f"obj_{snake}"
        masked: dict[str, list[str]] = {}
        for rn in roles:
            acc = o.roles[rn].types.get(t)
            if acc:
                for m in acc.mask:
                    masked.setdefault(m, []).append(rn)
        cols = ["id"]
        for p in o.object_types[t].properties:
            if p.name in masked:
                inl = ", ".join(lit(r) for r in masked[p.name])
                cols.append(f"CASE WHEN {ROLE_SQL} IN ({inl}) THEN NULL ELSE {q(p.name)} END AS {q(p.name)}")
            else:
                cols.append(q(p.name))
        cols += ["valid_during", "recorded_during", "changed_by", "action_id", "scenario_id"]
        sel = ",\n  ".join(cols)
        for view, src in ((f"rd_{tbl}", tbl), (f"rd_cur_{tbl}", f"cur_{tbl}"), (f"rd_eff_{tbl}", f"eff_{tbl}")):
            out += [f"CREATE OR REPLACE VIEW {view} WITH (security_invoker = true) AS",
                    f"SELECT {sel}\nFROM {src};"]
        out.append("")

    # 5. grants (no DELETE/TRUNCATE anywhere)
    out.append(f"-- grants for {APP_ROLE}")
    tbls = [f"obj_{snake_case(t)}" for t in types] + [f"link_{ln}" for ln in sorted(o.link_types)]
    views = [f"cur_{x}" for x in tbls] + [f"eff_{x}" for x in tbls] + [f"rd_{x}" for x in tbls if x.startswith("obj_")] \
        + [f"rd_cur_{x}" for x in tbls if x.startswith("obj_")] + [f"rd_eff_{x}" for x in tbls if x.startswith("obj_")]
    if tbls:
        out.append(f"GRANT SELECT ON {', '.join(tbls + views)} TO {APP_ROLE};")
        out.append(f"GRANT INSERT, UPDATE ON {', '.join(tbls)} TO {APP_ROLE};")
        out.append(f"REVOKE DELETE, TRUNCATE ON {', '.join(tbls)} FROM {APP_ROLE};")
    out += [f"GRANT INSERT ON graph_outbox TO {APP_ROLE};",
            f"GRANT USAGE ON SEQUENCE graph_outbox_seq_seq TO {APP_ROLE};",
            f"GRANT SELECT ON ontology_registry TO {APP_ROLE};", ""]
    return "\n".join(out)
