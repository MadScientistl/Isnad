from __future__ import annotations

from .model import Ontology

PY = {"string": "str", "int": "int", "float": "float", "bool": "bool", "timestamp": "datetime"}
TS = {"string": "string", "int": "number", "float": "number", "bool": "boolean", "timestamp": "string"}


def pydantic_source(o: Ontology) -> str:
    out = ["# Generated by engine.compiler. Do not edit.",
           "from datetime import datetime", "from typing import Literal, Optional", "from uuid import UUID", "",
           "from pydantic import BaseModel", ""]
    names = []
    for n in sorted(o.object_types):
        names.append(n)
        out += ["", f"class {n}(BaseModel):", "    id: UUID"]
        for p in o.object_types[n].properties:
            if p.type == "enum":
                t = "Literal[" + ", ".join(repr(v) for v in p.enum) + "]"
            else:
                t = PY[p.type]
            out.append(f"    {p.name}: {t}" if p.required else f"    {p.name}: Optional[{t}] = None")
    out += ["", "", "class Link(BaseModel):", "    src: UUID", "    dst: UUID", "",
            "", "OBJECT_MODELS = {" + ", ".join(f"{n!r}: {n}" for n in names) + "}", ""]
    return "\n".join(out)


def ts_source(o: Ontology) -> str:
    out = ["// Generated by engine.compiler. Do not edit.", ""]
    for n in sorted(o.object_types):
        out.append(f"/** Writable properties of {n}. */")
        out.append(f"export interface {n}Props {{")
        for p in o.object_types[n].properties:
            t = " | ".join(repr(v).replace("'", '"') for v in p.enum) if p.type == "enum" else TS[p.type]
            out.append(f"  {p.name}{'' if p.required else '?'}: {t};")
        out += ["}", "", f"export interface {n} extends {n}Props {{",
                "  id: string;", "  valid_from: string;", "  valid_to: string | null;",
                "  changed_by: string;", "}", ""]
    types = sorted(o.object_types)
    links = sorted(o.link_types)
    out.append("export type ObjectTypeName = " + (" | ".join(f'"{t}"' for t in types) or "never") + ";")
    out.append("export type LinkTypeName = " + (" | ".join(f'"{t}"' for t in links) or "never") + ";")
    out.append("export interface ObjectTypeMap {")
    out += [f"  {t}: {t};" for t in types]
    out.append("}")
    out.append("export interface ObjectPropsMap {")
    out += [f"  {t}: {t}Props;" for t in types]
    out.append("}")
    out.append(TS_RUNTIME)
    return "\n".join(out)


TS_RUNTIME = r"""
export type DateLike = string | Date;
export type Role = string;

export type HistoryRow<T> = T & { recorded_from: string; recorded_to: string | null };
export interface LinkRow { src: string; dst: string }
export interface Neighbour {
  link: LinkTypeName;
  direction: "out" | "in";
  type: ObjectTypeName;
  id: string;
  object: ObjectTypeMap[ObjectTypeName] | null;
}
export interface TypesResponse {
  namespace: string;
  classes: Record<string, { extends: string | null }>;
  objectTypes: {
    name: string;
    properties: { name: string; type: string; required: boolean; enum: string[] }[];
  }[];
  linkTypes: {
    name: string; from: string; to: string; cardinality: string;
    required: boolean; transitive: boolean; inverse: string | null;
  }[];
  role: string;
}
export interface ListOptions { limit?: number; offset?: number; asOfValid?: DateLike; asOfRecorded?: DateLike }
export interface GetOptions { asOfValid?: DateLike; asOfRecorded?: DateLike }
export interface LinksOptions { id?: string; direction?: "out" | "in"; asOf?: DateLike; asOfRecorded?: DateLike }
export interface WriteOptions { id?: string; valid_from?: DateLike }

export class ApiError extends Error {
  constructor(public status: number, public detail: unknown) {
    super(`API ${status}: ${typeof detail === "string" ? detail : JSON.stringify(detail)}`);
  }
}

function iso(d: DateLike): string {
  return d instanceof Date ? d.toISOString() : d;
}

function qs(params: Record<string, string | number | Date | undefined>): string {
  const u = new URLSearchParams();
  for (const [k, v] of Object.entries(params)) {
    if (v !== undefined) u.set(k, v instanceof Date ? v.toISOString() : String(v));
  }
  const s = u.toString();
  return s ? `?${s}` : "";
}

export class OntologyClient {
  constructor(public baseUrl: string = "http://localhost:8000", public role?: Role) {}

  setRole(role: Role | undefined): void {
    this.role = role;
  }

  private async req<T>(path: string, init: RequestInit = {}): Promise<T> {
    const headers: Record<string, string> = { "content-type": "application/json" };
    if (this.role) headers["x-role"] = this.role;
    const r = await fetch(this.baseUrl.replace(/\/$/, "") + path, { ...init, headers });
    if (!r.ok) {
      let detail: unknown = await r.text();
      try { detail = (JSON.parse(detail as string) as { detail?: unknown }).detail ?? detail; } catch { /* text */ }
      throw new ApiError(r.status, detail);
    }
    return r.json() as Promise<T>;
  }

  types(): Promise<TypesResponse> {
    return this.req("/types");
  }

  list<K extends ObjectTypeName>(type: K, o: ListOptions = {}): Promise<ObjectTypeMap[K][]> {
    return this.req(`/objects/${type}` + qs({
      limit: o.limit, offset: o.offset,
      as_of_valid: o.asOfValid && iso(o.asOfValid), as_of_recorded: o.asOfRecorded && iso(o.asOfRecorded),
    }));
  }

  get<K extends ObjectTypeName>(type: K, id: string, o: GetOptions = {}): Promise<ObjectTypeMap[K]> {
    return this.req(`/objects/${type}/${id}` + qs({
      as_of_valid: o.asOfValid && iso(o.asOfValid), as_of_recorded: o.asOfRecorded && iso(o.asOfRecorded),
    }));
  }

  create<K extends ObjectTypeName>(type: K, props: ObjectPropsMap[K], o: WriteOptions = {}): Promise<ObjectTypeMap[K]> {
    const body = { ...props, ...(o.id ? { id: o.id } : {}), ...(o.valid_from ? { valid_from: iso(o.valid_from) } : {}) };
    return this.req(`/objects/${type}`, { method: "POST", body: JSON.stringify(body) });
  }

  replace<K extends ObjectTypeName>(type: K, id: string, props: ObjectPropsMap[K], o: { valid_from?: DateLike } = {}): Promise<ObjectTypeMap[K]> {
    const body = { ...props, ...(o.valid_from ? { valid_from: iso(o.valid_from) } : {}) };
    return this.req(`/objects/${type}/${id}`, { method: "PUT", body: JSON.stringify(body) });
  }

  remove(type: ObjectTypeName, id: string): Promise<{ deleted: string }> {
    return this.req(`/objects/${type}/${id}`, { method: "DELETE" });
  }

  history<K extends ObjectTypeName>(type: K, id: string): Promise<HistoryRow<ObjectTypeMap[K]>[]> {
    return this.req(`/objects/${type}/${id}/history`);
  }

  links(link: LinkTypeName, o: LinksOptions = {}): Promise<LinkRow[]> {
    return this.req(`/links/${link}` + qs({
      id: o.id, direction: o.direction,
      as_of: o.asOf && iso(o.asOf), as_of_recorded: o.asOfRecorded && iso(o.asOfRecorded),
    }));
  }

  createLink(link: LinkTypeName, src: string, dst: string, valid_from?: DateLike): Promise<LinkRow> {
    return this.req(`/links/${link}`, {
      method: "POST",
      body: JSON.stringify({ src, dst, ...(valid_from ? { valid_from: iso(valid_from) } : {}) }),
    });
  }

  removeLink(link: LinkTypeName, src: string, dst: string): Promise<{ deleted: LinkRow }> {
    return this.req(`/links/${link}` + qs({ src, dst }), { method: "DELETE" });
  }

  neighbours(type: ObjectTypeName, id: string, asOf?: DateLike): Promise<Neighbour[]> {
    return this.req(`/neighbours/${type}/${id}` + qs({ as_of: asOf && iso(asOf) }));
  }
}
"""
